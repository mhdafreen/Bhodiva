import React, { useState } from 'react';
import { Stethoscope, Printer, Copy, Check, Share2, HelpCircle } from 'lucide-react';
import { MedicalReportData } from '../../types/medicalReport';

interface DoctorPrepSheetProps {
  report: MedicalReportData;
}

export const DoctorPrepSheet: React.FC<DoctorPrepSheetProps> = ({ report }) => {
  const [copied, setCopied] = useState(false);

  const handlePrint = () => {
    window.print();
  };

  const handleCopy = () => {
    const text = `BODHIVA Healthcare Discussion Prep Sheet
Report: ${report.metadata.reportCategory} (${report.metadata.reportDate || 'Date: N/A'})
Laboratory: ${report.metadata.labName || 'N/A'}

QUESTIONS FOR MY DOCTOR:
${report.questionsForDoctor.map((q, idx) => `${idx + 1}. ${q}`).join('\n')}

SUMMARY OF FINDINGS:
${report.summary.importantFindings.map(f => `• ${f}`).join('\n')}

*Generated by Bodhiva for patient health literacy. Educational only, not a medical diagnosis.`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleShareWhatsApp = () => {
    const text = encodeURIComponent(
      `*Bodhiva Doctor Discussion Notes*\nReport: ${report.metadata.reportCategory}\n\n*Questions to ask the doctor:*\n${report.questionsForDoctor.map((q, idx) => `${idx + 1}. ${q}`).join('\n')}`
    );
    window.open(`https://api.whatsapp.com/send?text=${text}`, '_blank');
  };

  return (
    <div className="bg-gradient-to-br from-blue-50/80 via-white to-blue-50/40 rounded-3xl border border-blue-200/90 shadow-md p-6 sm:p-8 space-y-6 print:border-none print:shadow-none print:p-0">
      {/* Top Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-4 border-b border-blue-100 gap-4">
        <div className="flex items-center gap-3.5">
          <div className="w-12 h-12 rounded-2xl bg-blue-600 text-white flex items-center justify-center shadow-md flex-shrink-0">
            <Stethoscope className="w-6 h-6" />
          </div>
          <div>
            <span className="text-[11px] font-bold uppercase tracking-wider text-blue-700 bg-blue-100/70 px-2.5 py-0.5 rounded-full">
              Consultation Readiness
            </span>
            <h3 className="text-xl font-extrabold text-blue-950 mt-1">
              Questions Prepared for Your Doctor
            </h3>
            <p className="text-xs text-blue-800/80 mt-0.5">
              Take these questions to your next clinical visit to discuss findings with confidence.
            </p>
          </div>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2 print:hidden">
          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-3 py-2 rounded-xl bg-white border border-slate-200 text-slate-700 hover:bg-slate-50 text-xs font-semibold shadow-sm transition"
            title="Copy questions to clipboard"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-600" /> : <Copy className="w-4 h-4" />}
            <span>{copied ? 'Copied' : 'Copy'}</span>
          </button>

          <button
            onClick={handleShareWhatsApp}
            className="flex items-center gap-1.5 px-3 py-2 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-800 hover:bg-emerald-100 text-xs font-semibold shadow-sm transition"
            title="Share via WhatsApp"
          >
            <Share2 className="w-4 h-4 text-emerald-600" />
            <span className="hidden sm:inline">WhatsApp</span>
          </button>

          <button
            onClick={handlePrint}
            className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-blue-600 hover:bg-blue-700 text-white text-xs font-bold shadow-md shadow-blue-600/20 transition"
          >
            <Printer className="w-4 h-4" />
            <span>Print Sheet</span>
          </button>
        </div>
      </div>

      {/* Questions Checklist */}
      <div className="space-y-3">
        {report.questionsForDoctor.map((question, idx) => (
          <div
            key={idx}
            className="bg-white p-4 sm:p-5 rounded-2xl border border-blue-100/90 shadow-sm flex items-start gap-3.5 hover:border-blue-300 transition-colors"
          >
            <div className="w-7 h-7 rounded-xl bg-blue-50 text-blue-700 font-extrabold text-xs flex items-center justify-center flex-shrink-0 mt-0.5 border border-blue-200">
              {idx + 1}
            </div>
            <p className="text-xs sm:text-sm font-semibold text-slate-800 leading-relaxed pt-0.5">
              "{question}"
            </p>
          </div>
        ))}
      </div>

      {/* Helpful clinical tips footer */}
      <div className="p-4 rounded-2xl bg-white/70 border border-blue-100 flex items-start gap-2.5 text-xs text-blue-900/90">
        <HelpCircle className="w-4 h-4 text-blue-600 flex-shrink-0 mt-0.5" />
        <p>
          <strong>Tip for your consultation:</strong> Bring previous blood test reports if you have them. Tracking how your parameters change over months is often more valuable to a doctor than a single isolated number.
        </p>
      </div>
    </div>
  );
};
